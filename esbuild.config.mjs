import esbuild from 'esbuild';
import process from 'process';
import fs from 'node:fs';
import { builtinModules, createRequire } from 'node:module';

const require = createRequire(import.meta.url);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [
		{
			name: 'inline-pdfjs-worker',
			setup(build) {
				build.onResolve({ filter: /pdfjs-dist\/build\/pdf\.worker/ }, (args) => {
					return {
						path: require.resolve(args.path),
						namespace: 'pdf-worker',
					};
				});
				build.onLoad({ filter: /.*/, namespace: 'pdf-worker' }, (args) => {
					const content = fs.readFileSync(args.path, 'utf-8');
					return { contents: content, loader: 'text' };
				});
			},
		},
		{
			name: 'strip-docx-ie-setimmediate',
			setup(build) {
				build.onResolve({ filter: /^docx$/ }, (args) => {
					return {
						path: require.resolve(args.path),
						namespace: 'docx-patched',
					};
				});
				build.onLoad({ filter: /.*/, namespace: 'docx-patched' }, async (args) => {
					let code = await fs.promises.readFile(args.path, 'utf8');

					const original = code;

					// 1. Disable IE6-8 detection — ternary always takes setTimeout branch
					code = code.replace(
						/"onreadystatechange" in t\.document\.createElement\("script"\)/g,
						'false'
					);
					code = code.replace(
						/"onreadystatechange" in l\.createElement\("script"\)/g,
						'false'
					);

					// 2. Remove dead createElement("script") calls in eliminated branches
					code = code.replace(
						/var e = t\.document\.createElement\("script"\);/,
						''
					);
					code = code.replace(
						/var t = l\.createElement\("script"\);/,
						''
					);

					if (code === original) {
						throw new Error(
							'docx IE polyfill patch failed: expected patterns not found. Has docx changed version?'
						);
					}

					return {
						contents: code,
						loader: 'js',
					};
				});
			},
		},
	],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
